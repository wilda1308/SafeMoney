    private void btnRetirarSumaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRetirarSumaActionPerformed
        int cantActualRetirar = Integer.parseInt(lblRetirarS.getText());
        double cantActual = Double.parseDouble(lblDineroServicios.getText());
        if(cantActualRetirar < cantActual){
            lblRetirarS.setText(String.valueOf(cantActualRetirar + 1000));
        }else{
            JOptionPane.showMessageDialog(this, "No se puede retirar una cantidad mayor a la que hay disponible en el bolsillo", "DINERO INSUFICIENTE PARA RETIRAR", HEIGHT);
        }
    }//GEN-LAST:event_btnRetirarSumaActionPerformed

    private void btnRetirarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRetirarActionPerformed
        int cantActualRetirar = Integer.parseInt(lblRetirarS.getText());
        double cantActual = Double.parseDouble(lblDineroServicios.getText());

        if (cantActualRetirar >= 0) {
            if(cantActualRetirar <= cantActual){
                cantActual -= cantActualRetirar;
                lblDineroServicios.setText(String.valueOf(cantActual));
                user.servicio.retirarCantidad(cantActualRetirar, cantActual);
                lblRetirarS.setText("0");
            }else{
                JOptionPane.showMessageDialog(this, "No se puede retirar una cantidad mayor a la disponible, por favor verifique la cantidad a retirar", "NO SE PUEDE RETIRAR", HEIGHT);
            }
        }else{
            JOptionPane.showMessageDialog(this, "No se puede retirar 0 a la cantidad, por favor verifique la cantidad a retirar", "NO SE PUEDE RETIRAR 0", HEIGHT);
        }
    }//GEN-LAST:event_btnRetirarActionPerformed

