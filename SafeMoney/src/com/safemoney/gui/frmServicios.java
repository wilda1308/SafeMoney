    private void btnAgregarRestaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarRestaActionPerformed
        int cantActual = Integer.parseInt(lblAgregarS.getText());

        if ( cantActual > 0) {
            lblAgregarS.setText(String.valueOf(cantActual - 1000));
        } else {
            JOptionPane.showMessageDialog(this, "No se puede disminuir la cantidad a numeros negativos, recuerda que para agregar dinero debe ser positivo.", "NO SE ACEPTA CANTIDADES NEGATIVAS", HEIGHT);
        }
    }//GEN-LAST:event_btnAgregarRestaActionPerformed

