    /*
    * Método que se ejecuta al presionar el boton de mostrar password (icono de ojo cerrado)
    */
    private void mostrarPassActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mostrarPassActionPerformed
        if(mostrarPass.isSelected()){ //Verifica si el botón mostrar parrword está seleccionado
            mostrarPass.setIcon(new javax.swing.ImageIcon(getClass().getResource("/com/safemoney/imagenes/ojoAbierto.png"))); //Modifica el icono a una nueva imagen tipo icono de una ruta o url dentro del proyecto (ojo abierto).
            passContraseña.setEchoChar((char)0); //Al llamar el metodo setEchoChar((char)0) permite mostrar la contraseña reemplazando todos los caracteres a caracteres visibles dentro del campo.
        }else{
            mostrarPass.setIcon(new javax.swing.ImageIcon(getClass().getResource("/com/safemoney/imagenes/ojoCerrado.png"))); //Modifica el icono a una nueva imagen de tipo icono de una ruta existente de una ruta o url dentro del proyecto (ojo cerrado) (icono por defecto).
            passContraseña.setEchoChar('*'); //Al modificar los caracteres por * cada uno se oculta con ese caracter.
        }
    }//GEN-LAST:event_mostrarPassActionPerformed
