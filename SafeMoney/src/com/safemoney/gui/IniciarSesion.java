    /*
    * Método que ocurre cuando hacemos click al botón Iniciar Sesión
    */
    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed
        //Creamos un nuevo usuario para validar la información con el usuario que se recupere de un método Iniciar Sesión.
        
        Usuario validar = new Usuario();
        //Primero validamos que ambos de los campos está con el mensaje por defecto.
        if(txtUsuario.getText().equals("Ingresar nombre o correo") || String.valueOf(passContraseña.getPassword()).equals("************")){
            //Mostramos un mensaje que los campos esán vacios.
            JOptionPane.showMessageDialog(this, "Los campos de Usuario y Contraseña están vacios", "CAMPOS VACIOS", HEIGHT);
        }
        else{ //En caso de que no sean igual al texto por defecto.
            //En el método inicarSesion busca el usuario que tenga estas igualdades y lo retorna, luego lo  almacenamos en una variable del mismo tipo Usuario.
            user = validar.iniciarSesion(txtUsuario.getText(), txtUsuario.getText(), String.valueOf(passContraseña.getPassword()), usuarios);
            //Validamos que el valor retornado no sea nulo
            if(user != null){
                //Crea una instancia de Inicio de la clase FrmPrincipal.
                FrmPrincipal inicio = new FrmPrincipal();
                //Lo hacemos visible.
                inicio.setVisible(true);
                //La ventana actual se volverá no visible.
                this.setVisible(false);
                
            }else{ //En aso de ser nulos mostrar un mensaje de Usuario o contraseña erroneas.
                //Mostramos un mensaje de que el usuario o contraseña no existen o son inválidos
                JOptionPane.showMessageDialog(this, "Usuario o contraseña invalidos o incorrectos.\nPor favor, verifica los campos y vuelve a intentar.", "USUARIO O CONTRASEÑA INVÁLIDOS", HEIGHT);
                
                //Reestablecemos el color y el texto de los campos de Usuario: y Contraseña:
                txtUsuario.setText("Ingresar nombre o correo"); //Modifica el texto a un texto por defecto
                txtUsuario.setForeground(new java.awt.Color(180,180,180)); //Modifica el color al color por defecto el cual es gris claro.
                passContraseña.setText("************"); //Modifica el texto a un texto por defecto
                passContraseña.setForeground(new java.awt.Color(180,180,180)); //Modifica el color al color por defecto el cual es gris claro.
            }
        }
    }//GEN-LAST:event_btnIniciarSesionActionPerformed
