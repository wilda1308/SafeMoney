    private void txtUsuarioMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_txtUsuarioMousePressed
        
        if(txtUsuario.getText().equals("Ingresar nombre o correo")){ //Valida si el texto del campo usuario es igual al texto por defecto.
            txtUsuario.setText(""); //Modifica el texto a vacio
            txtUsuario.setForeground(Color.BLACK); //Modifica el color del texto a negro.
        }
        if(String.valueOf(passContraseña.getPassword()).isEmpty()){ //Realiza el parseo a cadena de texto, y valida si el campo está vacio.
            passContraseña.setText("************"); //Modifica el texto al texto por defecto.
            passContraseña.setForeground(new java.awt.Color(180,180,180)); //Modifica el color del texto a gris claro (Color por defecto).
        }
    }//GEN-LAST:event_txtUsuarioMousePressed
