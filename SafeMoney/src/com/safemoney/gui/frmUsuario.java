    /*
    * Método que se ejecuta cuando se presiona alguna tecla dentro del campo de contraseña
    */
    private void passContraseñaKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_passContraseñaKeyPressed
        //Validamos que el campo contraseña sea editable y al mismo tiempo que la tecla que se haya presionado sea igual a la tecla enter <-
        if(passContraseña.isEditable() && evt.getKeyCode() == KeyEvent.VK_ENTER){
            //Parseamos la contraseña para validar si el campo de contraseña esta vacio.
            if(String.valueOf(passContraseña.getPassword()).isEmpty()){
                //Mostramos un mensaje donde diga que el campo de contraseña no puede estar vacio.
                JOptionPane.showMessageDialog(this, "El campo de Contraseña no puede estar vacio, coloca una contraseña", "CAMPO VACIO", HEIGHT);
            }
            else{ //Si no se cumple esta condición
                //Parseamos el valor de la contraseña y validamos que la cantidad de cáracteres supere el valor de 8.
                if(String.valueOf(passContraseña.getPassword()).length() >= 8){ //Valida que la contraseña sea mayor o igual a 8 caracteres para tener una contraseña segura.
                    contraseña = String.valueOf(passContraseña.getPassword()); //A la variable global contraseña, le asignamos un nuevo valor del parseo de la contraseña a cadena de texto.
                    user.setContraseña(contraseña); //Modificamos la contraseña del usuario que esta actualmente en sesión.
                    IniciarSesion.usuarios.set(id, user); //Del ArrayList (donde estamos almacenando los usuarios) modificar segun el id del usuario (de la sesion actual) a la instancia que recientemente creamos.
                    passContraseña.setEditable(false); //Modificamos la edición del campo de la contraseña, para que no se pueda editar
                    //Mostramos un mensaje qye se actualizó la contrasseña con éxito.
                    JOptionPane.showMessageDialog(this, "Se actualizó la contraseña " + contraseña + " con éxito", "ACTUALIZACIÓN CORRECTA", JOptionPane.INFORMATION_MESSAGE);
                }else{
                    //En caso de no cumplir con la condición de contraseña se muestra un mensaje de error
                    JOptionPane.showMessageDialog(this, "Contraseña invalida, por favor crea una contraseña de mínimo 8 cáracteres.\n(Por ejemplo: My_contraseña123)", "CONTRASEÑA CORTA", JOptionPane.HEIGHT);
                    //Modificamos el texto del campo de contraseña y le dejamos la contraseña que tenia antes de editar.
                    passContraseña.setText(contraseña);
                    //Modificamos la edicion del campo contraseña para que no se pueda editar el campo
                    passContraseña.setEditable(false);
                }
            }
        }
    }//GEN-LAST:event_passContraseñaKeyPressed
