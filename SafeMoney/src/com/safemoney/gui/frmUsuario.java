    /*
    * Método que se ejecuta al presionar una tecla en el campo de nombre
    */
    private void txtNombreKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtNombreKeyPressed

        
        if(txtNombre.isEditable() && evt.getKeyCode() == KeyEvent.VK_ENTER){ //Valida que el campo de nombre sea editable y al mismo tiempo que al obtener la tecla presionada sea igual a la tecla enter <-
            if(!txtNombre.getText().isEmpty()){ //Valida que el campo de nombre no sea vacio
                if(txtNombre.getText().length() >= 3){
                    nombre = txtNombre.getText(); //A la variable global nombre se le asigna un nuevo valor que es el texto del campo nombre que se modifique
                    user.setNombre(nombre); //Al nombre de user (el usuario que se inició sesión) se le modifica el nombre.
                    usuarios.set(id, user); //Modificamos todo el usuario del id actual (La sesión actual) y se cambia con el usuario que acabamos de instanciar al ArrayList de usuarios.
                    txtNombre.setEditable(false); //Modificamos la edición para que no se pueda editar
                    //Por ultimo mostramos un mensaje de que se actualizo el nombre con éxito.
                    JOptionPane.showMessageDialog(this, "Se actualizó el nombre " + nombre + " con éxito", "ACTUALIZACIÓN CORRECTA", JOptionPane.INFORMATION_MESSAGE);
                }else{
                    //En caso de no cumplir con la condición de nombre se muestra un mensaje de error y sereestablece los valores para que el usuario vuelva a digitar el nombre.
                    JOptionPane.showMessageDialog(this, "El nombre debe tener más de tres carácteres, no puede haber un nombre de uno o dos carácteres.", "NOMBRE DEMASIADO CORTO", JOptionPane.HEIGHT);
                    txtNombre.setText(nombre);
                }  
            }else{ //En caso de que el campo este vacio que muestre un mensaje de que el campo se encuentra vacio.
                JOptionPane.showMessageDialog(this, "El campo de nombre no puede estar vacio, por favor coloca un nombre", "CAMPO VACIO", HEIGHT);
            }
        }
    }//GEN-LAST:event_txtNombreKeyPressed
